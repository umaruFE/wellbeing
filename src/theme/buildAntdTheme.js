import { theme as antdTheme } from 'antd';
import { workbenchTokens as w } from './workbenchTokens.js';
import { borderRadius, size, space, typography } from './theme.js';

/** Shared workbench theme. Legacy Figma exports remain as source history only. */
export function buildAntdTheme({ colorMode = 'light', density = 'default' } = {}) {
  const compact = density === 'compact';
  const dark = colorMode !== 'light';
  return {
    algorithm: dark ? antdTheme.darkAlgorithm : antdTheme.defaultAlgorithm,
    token: {
      colorPrimary: w.primary,
      colorPrimaryHover: w['primary-hover'],
      colorPrimaryActive: w['primary-active'],
      colorPrimaryBg: w.selected,
      colorPrimaryBgHover: '#e9e0fc',
      colorPrimaryBorder: w['selected-border'],
      colorPrimaryBorderHover: w.primary,
      colorLink: w['primary-hover'],
      colorLinkHover: w.primary,
      colorLinkActive: w['primary-active'],
      ...(!dark && {
        colorText: w.text,
        colorTextBase: w.text,
        colorTextSecondary: w.muted,
        colorTextTertiary: w.muted,
        colorTextQuaternary: w.placeholder,
        colorTextPlaceholder: w.placeholder,
        colorBorder: w.border,
        colorBorderSecondary: w['border-soft'],
        colorSplit: w['border-soft'],
        colorBgLayout: w.page,
        colorBgContainer: w.surface,
        colorBgElevated: w.surface,
        colorBgContainerDisabled: w.page,
        colorBgTextHover: w.selected,
      }),
      fontFamily: w.font,
      fontSize: typography.fontSize.DEFAULT,
      fontSizeSM: typography.fontSize.sm,
      fontSizeLG: typography.fontSize.lg,
      fontSizeHeading1: typography.fontSize.heading1,
      fontSizeHeading2: typography.fontSize.heading2,
      fontSizeHeading3: typography.fontSize.heading3,
      fontSizeHeading4: typography.fontSize.heading4,
      fontSizeHeading5: typography.fontSize.lg,
      fontWeightStrong: typography.fontWeight.strong,
      lineHeight: 1.6,
      borderRadius: borderRadius.DEFAULT,
      borderRadiusSM: borderRadius.sm,
      borderRadiusLG: borderRadius.lg,
      lineWidth: 1,
      controlHeight: compact ? size.height.sm : size.height.lg,
      controlHeightSM: size.height.sm,
      controlHeightLG: 48,
      controlOutline: w['selected-border'],
      controlOutlineWidth: size.lineWidth.controlOutline,
      controlItemBgActive: w.selected,
      controlItemBgHover: w.page,
      colorSuccess: '#43866a',
      colorWarning: '#b77b25',
      colorError: '#b74860',
      boxShadow: w['shadow-dialog'],
      boxShadowSecondary: w['shadow-dialog'],
    },
    components: {
      Button: {
        controlHeight: compact ? size.height.sm : size.height.DEFAULT,
        controlHeightSM: size.height.sm,
        controlHeightLG: size.height.lg,
        paddingInline: 14,
        fontWeight: typography.fontWeight.strong,
        defaultShadow: 'none',
        primaryShadow: 'none',
        dangerShadow: 'none',
        defaultBorderColor: w.border,
        defaultColor: w.text,
        defaultHoverBg: w.selected,
        defaultHoverColor: w['primary-hover'],
        defaultHoverBorderColor: w['selected-border'],
        defaultActiveBg: w.selected,
        defaultActiveColor: w['primary-active'],
        defaultActiveBorderColor: w['selected-border'],
      },
      Input: { activeShadow: `0 0 0 3px ${w.selected}`, paddingBlock: space.padding.xs, paddingInline: space.padding.sm },
      Select: { optionSelectedBg: w.selected, optionSelectedColor: w['primary-hover'] },
      Card: { borderRadiusLG: borderRadius.lg, headerFontSize: typography.fontSize.heading4, headerHeight: 56 },
      Modal: { borderRadiusLG: borderRadius.xxl, titleFontSize: typography.fontSize.heading3, paddingContentHorizontalLG: space.padding.lg },
      Tabs: { itemSelectedColor: w['primary-hover'], inkBarColor: w.primary, horizontalItemGutter: space.padding.lg, titleFontSize: typography.fontSize.DEFAULT },
      Table: { headerBg: w.page, headerColor: w.muted, rowHoverBg: w.selected, cellPaddingBlock: space.padding.DEFAULT },
      Segmented: { itemSelectedBg: w.surface, itemSelectedColor: w['primary-hover'], trackBg: w.page, borderRadius: 10 },
      Menu: { itemSelectedBg: w.selected, itemSelectedColor: w['primary-hover'], itemBorderRadius: 10 },
    },
  };
}

export const appAntdTheme = buildAntdTheme();
