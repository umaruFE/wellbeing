def replace_visible_text(paragraph, new_text):
    nodes = paragraph._p.xpath('.//w:t')
    if not nodes:
        paragraph.add_run(new_text)
        return
    nodes[0].text = new_text
    for node in nodes[1:]:
        node.text = ''


def replace_text_fragment(paragraph, old_text, new_text):
    for node in paragraph._p.xpath('.//w:t'):
        if old_text in (node.text or ''):
            node.text = node.text.replace(old_text, new_text)
            return True
    return False


def main():
    doc = Document(SOURCE)
    replaced = set()

    for paragraph in doc.paragraphs:
        old = paragraph.text
        if old in REPLACEMENTS:
            replace_visible_text(paragraph, REPLACEMENTS[old])
            replaced.add(old)

    for table in doc.tables:
        for row in table.rows:
            for cell in row.cells:
                for paragraph in cell.paragraphs:
                    old = paragraph.text
                    if old in REPLACEMENTS:
                        replace_visible_text(paragraph, REPLACEMENTS[old])
                        replaced.add(old)

    # 页眉页脚中的版本信息不在 doc.paragraphs 中，需按节单独处理。
    for section in doc.sections:
        for story in (section.header, section.footer):
            for paragraph in story.paragraphs:
                replace_text_fragment(
                    paragraph,
                    "V2026.09.16-R1  |  2026-09-16",
                    "V2026.09.20-R2  |  2026-09-20",
                )
                old = paragraph.text
                if old in REPLACEMENTS:
                    replace_visible_text(paragraph, REPLACEMENTS[old])
                    replaced.add(old)
            for table in story.tables:
                for row in table.rows:
                    for cell in row.cells:
                        for paragraph in cell.paragraphs:
                            old = paragraph.text
                            if old in REPLACEMENTS:
                                replace_visible_text(paragraph, REPLACEMENTS[old])
                                replaced.add(old)

    missing = sorted(set(REPLACEMENTS) - replaced)
    if missing:
        raise RuntimeError("未找到以下待替换文本：\n" + "\n".join(missing))

    # 目录中的三个名称位于超链接/单元格内，使用包含式替换以保留链接。
    for table in doc.tables:
        for row in table.rows:
            for cell in row.cells:
                for paragraph in cell.paragraphs:
                    text = paragraph.text
                    directory_updates = {
                        "1  AI 绘本制作": "1  AI 绘本制作（已实现）",
                        "2  星光音乐棚": "2  星光录音棚（已实现）",
                        "3  歌曲编唱屋": "3  歌曲编唱屋（已实现）",
                    }
                    if text in directory_updates:
                        replace_visible_text(paragraph, directory_updates[text])

    doc.save(OUTPUT)
    print(OUTPUT)


if __name__ == "__main__":
    main()
